// Before/after screenshots of the web client. Node 22+, no dependencies.
//
//   node tools/shots/run.mjs <base-ref> <head-ref> [out-dir] [--fonts] [--keep] [--only=id,id]
//
// Each ref's web/ and extraction/src/ are exported with `git archive` into
// <out-dir>/src/, never touching the checkout. web/lib/db.js is replaced by a
// fake generated from that ref's own export list (fake.js + fixture.json), so
// both sides render the same data and nothing reaches Supabase or the
// Anthropic API. A local Chrome or Edge is driven headless over the DevTools
// protocol. Every request that is not to localhost is answered empty in the
// page (--fonts lets Google Fonts through). Output: before/*.png,
// after/*.png and manifest.json in <out-dir>.

import { execFileSync, spawn } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { dirname, extname, join, normalize, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const argv = process.argv.slice(2);
const flags = new Set(argv.filter((a) => a.startsWith("--")).map((a) => a.split("=")[0]));
const only = argv.find((a) => a.startsWith("--only="))?.slice(7).split(",");
const [BASE, HEAD, outArg] = argv.filter((a) => !a.startsWith("--"));
if (!BASE || !HEAD) {
  console.error("usage: node tools/shots/run.mjs <base-ref> <head-ref> [out-dir] [--fonts] [--keep] [--only=id,id]");
  process.exit(2);
}
const OUT = resolve(outArg ?? join(HERE, "out"));
const CAP_HEIGHT = 12000;   // px; a full page taller than this is cut
const git = (...a) => execFileSync("git", a, { maxBuffer: 1 << 30 });

// ---------------------------------------------------------------- export

// git archive writes a tar; this reads it, so no tar binary is needed (Git
// Bash's tar takes "C:" for a remote host). Handles ustar prefixes and pax
// path records, which is all git archive emits.
function untar(buf, dest) {
  let paxPath = null;
  for (let o = 0; o + 512 <= buf.length;) {
    const h = buf.subarray(o, o + 512);
    if (h.every((b) => b === 0)) break;
    const str = (a, b) => h.subarray(a, b).toString("utf8").replace(/\0.*$/s, "");
    const size = parseInt(str(124, 136).trim() || "0", 8);
    const type = String.fromCharCode(h[156] || 48);
    const body = buf.subarray(o + 512, o + 512 + size);
    o += 512 + Math.ceil(size / 512) * 512;
    if (type === "x") { paxPath = /\d+ path=([^\n]*)\n/.exec(body.toString("utf8"))?.[1] ?? null; continue; }
    if (type === "g") continue;
    const prefix = str(345, 500);
    const name = paxPath ?? (prefix ? `${prefix}/${str(0, 100)}` : str(0, 100));
    paxPath = null;
    const path = join(dest, ...name.split("/"));
    if (type === "5") mkdirSync(path, { recursive: true });
    else if (type === "0" || type === "7") { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, body); }
  }
}

// The fake db.js: every name the real one exports (and every name app.js
// imports from it), each backed by fake.js. ideas() and sharedIdeas() changed
// shape between refs: an array of rows, or { ideas, caps } once the
// capability rows were embedded. Which one is read off the real function's
// body: `withCaps(` or a `{ ideas` literal means the split shape.
function fakeDb(realDb, appJs) {
  const names = new Set();
  for (const m of realDb.matchAll(/^export\s+(?:async\s+)?(?:function\*?|const|let)\s+(\w+)/gm)) names.add(m[1]);
  const imported = new Set();
  for (const m of appJs.matchAll(/import\s*\{([^}]*)\}\s*from\s*["']\.\/lib\/db\.js["']/g)) {
    for (const part of m[1].split(",")) { const n = part.trim().split(/\s+as\s+/)[0]; if (n) imported.add(n); }
  }
  const extra = [...imported].filter((n) => !names.has(n));
  extra.forEach((n) => names.add(n));
  const body = (name) => {
    const at = realDb.search(new RegExp(`^export\\s+(?:async\\s+)?function\\s+${name}\\b`, "m"));
    if (at < 0) return "";
    const next = realDb.slice(at + 1).search(/^export\s/m);
    return realDb.slice(at, next < 0 ? undefined : at + 1 + next);
  };
  const shape = (n) => (/withCaps\(|\{\s*ideas\s*[,:]/.test(body(n)) ? "split" : "rows");
  const shapes = { ideas: shape("ideas"), sharedIdeas: shape("sharedIdeas") };
  const lines = [
    "// Generated by tools/shots/run.mjs: the fake backend. Not the real db.js.",
    'import { fake } from "./__shots_fake.js";',
    `const f = fake({ shapes: ${JSON.stringify(shapes)} });`,
    ...[...names].sort().map((n) => (n === "db" ? "export const db = f.db;" : `export const ${n} = f.fn(${JSON.stringify(n)});`))
  ];
  return { src: lines.join("\n") + "\n", names: [...names], extra, shapes };
}

function exportRef(ref, side) {
  const sha = git("rev-parse", "--verify", `${ref}^{commit}`).toString().trim();
  const dir = join(OUT, "src", side);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  untar(git("archive", "--format=tar", sha, "web", "extraction/src"), dir);
  const web = join(dir, "web");
  const realDb = readFileSync(join(web, "lib", "db.js"), "utf8");
  const appJs = readFileSync(join(web, "app.js"), "utf8");
  const fk = fakeDb(realDb, appJs);
  writeFileSync(join(web, "lib", "db.js"), fk.src);
  writeFileSync(join(web, "lib", "__shots_fake.js"), readFileSync(join(HERE, "fake.js")));
  writeFileSync(join(web, "lib", "__shots_fixture.js"), `export default ${readFileSync(join(HERE, "fixture.json"), "utf8")};\n`);
  // placeholders only; the fake never reads them
  writeFileSync(join(web, "config.js"), 'export const SUPABASE_URL = "http://127.0.0.1:9";\nexport const SUPABASE_ANON_KEY = "shots-placeholder";\nexport const COMMIT = "shots";\n');
  const routes = new Set([...(/const ROUTES\s*=\s*new Set\(\[([^\]]*)\]/.exec(appJs)?.[1] ?? "").matchAll(/["'](\w+)["']/g)].map((m) => m[1]));
  console.log(`${side}: ${ref} @ ${sha.slice(0, 7)}, ${fk.names.length} db exports faked, ideas() shape ${fk.shapes.ideas}${fk.extra.length ? `, imported but not exported: ${fk.extra.join(", ")}` : ""}`);
  return { ref, sha, dir, routes, shapes: fk.shapes };
}

// ---------------------------------------------------------------- serve

const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8", ".json": "application/json", ".svg": "image/svg+xml", ".png": "image/png",
  ".jpg": "image/jpeg", ".webp": "image/webp", ".mp4": "video/mp4", ".webm": "video/webm", ".ico": "image/x-icon", ".woff2": "font/woff2" };

// web/ at the root and extraction/src/ mounted, the way web/serve.mjs does it
function serve(dir) {
  const web = join(dir, "web"), ext = join(dir, "extraction", "src");
  const server = createServer(async (req, res) => {
    try {
      const p = decodeURIComponent(new URL((req.url || "/").replace(/^\/+/, "/"), "http://x").pathname);
      const [base, rest] = p.startsWith("/extraction/src/") ? [ext, p.slice(16)] : [web, p];
      const rel = normalize(rest).replace(/^[/\\]+/, "");
      if (rel.split(sep).includes("..")) { res.writeHead(403).end(); return; }
      const file = join(base, rel || "index.html");
      const body = await readFile(file);
      const type = TYPES[extname(file)] ?? "application/octet-stream";
      const range = /^bytes=(\d*)-(\d*)$/.exec(req.headers.range ?? "");
      if (range && body.length) {
        const start = range[1] ? Number(range[1]) : Math.max(0, body.length - Number(range[2]));
        const end = range[1] && range[2] ? Math.min(Number(range[2]), body.length - 1) : body.length - 1;
        res.writeHead(206, { "content-type": type, "accept-ranges": "bytes", "content-range": `bytes ${start}-${end}/${body.length}`, "content-length": end - start + 1 })
          .end(body.subarray(start, end + 1));
        return;
      }
      res.writeHead(200, { "content-type": type, "cache-control": "no-store", "accept-ranges": "bytes", "content-length": body.length }).end(body);
    } catch (e) {
      res.writeHead(e.code === "ENOENT" || e.code === "EISDIR" ? 404 : 500).end();
    }
  });
  return new Promise((ok) => server.listen(0, "127.0.0.1", () => ok({ server, port: server.address().port })));
}

// ---------------------------------------------------------------- browser

function findBrowser() {
  if (process.env.SHOTS_BROWSER) return process.env.SHOTS_BROWSER;
  const c = [];
  if (process.platform === "win32") {
    const roots = [process.env.PROGRAMFILES, process.env["PROGRAMFILES(X86)"], process.env.LOCALAPPDATA].filter(Boolean);
    for (const r of roots) for (const p of ["Google/Chrome/Application/chrome.exe", "Microsoft/Edge/Application/msedge.exe",
      "Chromium/Application/chrome.exe", "BraveSoftware/Brave-Browser/Application/brave.exe"]) c.push(join(r, p));
  } else if (process.platform === "darwin") {
    for (const a of ["Google Chrome", "Chromium", "Microsoft Edge", "Brave Browser"]) c.push(`/Applications/${a}.app/Contents/MacOS/${a}`);
  } else {
    c.push("/usr/bin/google-chrome", "/usr/bin/google-chrome-stable", "/usr/bin/chromium", "/usr/bin/chromium-browser", "/usr/bin/microsoft-edge");
  }
  const hit = c.find((p) => existsSync(p));
  if (!hit) throw new Error("No Chrome, Edge or Chromium found. Set SHOTS_BROWSER to its binary.");
  return hit;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function launch(bin) {
  const profile = join(OUT, "browser-profile");
  rmSync(profile, { recursive: true, force: true });
  mkdirSync(profile, { recursive: true });
  const proc = spawn(bin, [
    "--headless=new", "--remote-debugging-port=0", `--user-data-dir=${profile}`,
    "--no-first-run", "--no-default-browser-check", "--disable-extensions", "--disable-sync",
    "--disable-background-networking", "--disable-component-update", "--disable-default-apps",
    "--metrics-recording-only", "--mute-audio", "--hide-scrollbars", "--force-color-profile=srgb",
    "--font-render-hinting=none", "about:blank"
  ], { stdio: "ignore" });
  const portFile = join(profile, "DevToolsActivePort");
  for (let i = 0; i < 100 && !existsSync(portFile); i++) await sleep(100);
  const [port, path] = readFileSync(portFile, "utf8").trim().split("\n");
  const ws = new WebSocket(`ws://127.0.0.1:${port}${path}`);
  await new Promise((ok, no) => { ws.onopen = ok; ws.onerror = no; });
  return { proc, profile, cdp: new CDP(ws) };
}

class CDP {
  constructor(ws) {
    this.ws = ws; this.id = 0; this.pending = new Map(); this.subs = new Map();
    ws.onmessage = ({ data }) => {
      const m = JSON.parse(data);
      if (m.id) {
        const p = this.pending.get(m.id); this.pending.delete(m.id);
        if (p) m.error ? p.no(new Error(`${p.method}: ${m.error.message}`)) : p.ok(m.result);
      } else this.subs.get(m.sessionId ?? "")?.(m.method, m.params);
    };
  }
  send(method, params = {}, sessionId) {
    const id = ++this.id;
    this.ws.send(JSON.stringify({ id, method, params, ...(sessionId ? { sessionId } : {}) }));
    return new Promise((ok, no) => {
      this.pending.set(id, { ok, no, method });
      setTimeout(() => { if (this.pending.delete(id)) no(new Error(`${method}: timed out`)); }, 30000);
    });
  }
}

const LOCAL = new Set(["127.0.0.1", "localhost", "[::1]"]);
const FONTS = new Set(["fonts.googleapis.com", "fonts.gstatic.com"]);

// One shot in a fresh browser context (its own storage), closed after.
async function shoot(cdp, { url, vp, theme, signedOut, steps = [], needsSelector, fullPage = true }) {
  const { browserContextId } = await cdp.send("Target.createBrowserContext", { disposeOnDetach: true });
  const { targetId } = await cdp.send("Target.createTarget", { url: "about:blank", browserContextId });
  const { sessionId } = await cdp.send("Target.attachToTarget", { targetId, flatten: true });
  const s = (m, p) => cdp.send(m, p, sessionId);
  const errors = [];
  const inflight = new Set();
  let lastNet = Date.now(), loaded = false;
  cdp.subs.set(sessionId, (method, p) => {
    if (method === "Fetch.requestPaused") {
      const host = new URL(p.request.url).hostname;
      const pass = LOCAL.has(host) || LOCAL.has(`[${host}]`) || (flags.has("--fonts") && FONTS.has(host));
      (pass ? s("Fetch.continueRequest", { requestId: p.requestId })
        : s("Fetch.fulfillRequest", { requestId: p.requestId, responseCode: 200, responseHeaders: [], body: "" })).catch(() => {});
    } else if (method === "Network.requestWillBeSent") {
      if (p.type !== "Media") { inflight.add(p.requestId); lastNet = Date.now(); }
    } else if (method === "Network.loadingFinished" || method === "Network.loadingFailed") {
      if (inflight.delete(p.requestId)) lastNet = Date.now();
    } else if (method === "Page.loadEventFired") loaded = true;
    else if (method === "Runtime.exceptionThrown") {
      const d = p.exceptionDetails;
      errors.push(d.exception?.description?.split("\n")[0] ?? d.text);
    } else if (method === "Runtime.consoleAPICalled" && p.type === "error") {
      errors.push(p.args.map((a) => a.value ?? a.description ?? "").join(" ").split("\n")[0]);
    } else if (method === "Log.entryAdded" && p.entry.level === "error") {
      errors.push(`${p.entry.text}${p.entry.url ? ` (${p.entry.url})` : ""}`);
    }
  });
  try {
    await Promise.all(["Page.enable", "Runtime.enable", "Log.enable", "Network.enable"].map((m) => s(m)));
    await s("Fetch.enable", { patterns: [{ urlPattern: "*" }] });
    await s("Emulation.setDeviceMetricsOverride", { width: vp.width, height: vp.height, deviceScaleFactor: 1, mobile: !!vp.mobile });
    if (vp.mobile) await s("Emulation.setTouchEmulationEnabled", { enabled: true, maxTouchPoints: 5 });
    await s("Emulation.setEmulatedMedia", { features: [
      { name: "prefers-color-scheme", value: theme }, { name: "prefers-reduced-motion", value: "reduce" }] });
    await s("Page.addScriptToEvaluateOnNewDocument", { source: `window.__SHOTS__ = ${JSON.stringify({ signedOut: !!signedOut })};` });
    await s("Page.navigate", { url });
    const settle = async () => {
      const t0 = Date.now();
      while (Date.now() - t0 < 15000 && !(loaded && inflight.size === 0 && Date.now() - lastNet > 500)) await sleep(100);
      // the app paints "Loading…" until its route's data is in
      for (let i = 0; i < 40; i++) {
        const { result } = await s("Runtime.evaluate", { expression: "/Loading( your [a-z]+)?…/.test(document.body?.innerText ?? '')", returnByValue: true });
        if (!result.value) break;
        await sleep(100);
      }
      await s("Runtime.evaluate", { expression: "document.fonts.ready.then(() => 1)", awaitPromise: true, returnByValue: true });
      await sleep(400);
    };
    await settle();
    if (needsSelector) {
      const { result } = await s("Runtime.evaluate", { expression: `!!document.querySelector(${JSON.stringify(needsSelector)})`, returnByValue: true });
      if (!result.value) return { missing: true, errors };
    }
    for (const st of steps) {
      if (st.click) {
        const { result } = await s("Runtime.evaluate", { expression: `(() => { const e = document.querySelector(${JSON.stringify(st.click)}); e?.click(); return !!e; })()`, returnByValue: true });
        if (!result.value) errors.push(`[shots] step: no element for ${st.click}`);
      } else if (st.key) {
        for (const type of ["keyDown", "keyUp"]) await s("Input.dispatchKeyEvent", { type, key: st.key, code: st.code ?? st.key });
      } else if (st.type) {
        await s("Input.insertText", { text: st.type });
      } else if (st.wait) await sleep(st.wait);
    }
    if (steps.length) await settle();
    // a playing video (the waifu scene) lands on a different frame each run,
    // and a focused field's caret blinks
    await s("Runtime.evaluate", { awaitPromise: true, expression: `document.head.append(Object.assign(document.createElement("style"),
      { textContent: "*, *::before, *::after { caret-color: transparent !important; }" })), Promise.all([...document.querySelectorAll("video")].map((v) => {
      v.pause(); if (!v.readyState || v.currentTime === 0) return 0;
      return new Promise((ok) => { v.addEventListener("seeked", ok, { once: true }); v.currentTime = 0; setTimeout(ok, 1000); });
    }))` });
    await sleep(100);
    const { cssContentSize: c } = await s("Page.getLayoutMetrics");
    const height = fullPage ? Math.min(CAP_HEIGHT, Math.max(vp.height, Math.ceil(c.height))) : vp.height;
    const { data } = await s("Page.captureScreenshot", { format: "png", captureBeyondViewport: true,
      clip: { x: 0, y: 0, width: vp.width, height, scale: 1 } });
    return { png: Buffer.from(data, "base64"), errors, cut: fullPage && c.height > CAP_HEIGHT };
  } finally {
    cdp.subs.delete(sessionId);
    await cdp.send("Target.closeTarget", { targetId }).catch(() => {});
    await cdp.send("Target.disposeBrowserContext", { browserContextId }).catch(() => {});
  }
}

// ---------------------------------------------------------------- main

const cfg = JSON.parse(readFileSync(join(HERE, "screens.json"), "utf8"));
mkdirSync(OUT, { recursive: true });
const sides = { before: exportRef(BASE, "before"), after: exportRef(HEAD, "after") };
for (const side of Object.keys(sides)) {
  rmSync(join(OUT, side), { recursive: true, force: true });
  mkdirSync(join(OUT, side), { recursive: true });
  Object.assign(sides[side], await serve(sides[side].dir));
}
const bin = findBrowser();
console.log(`browser: ${bin}`);
const browser = await launch(bin);

const shots = [];
try {
  for (const sc of cfg.screens) {
    if (only && !only.includes(sc.id)) continue;
    for (const [vpName, vp] of Object.entries(cfg.viewports)) {
      for (const theme of sc.dark ? ["light", "dark"] : ["light"]) {
        const id = `${sc.id}-${vpName}-${theme}`;
        const rec = { id, title: sc.title, route: sc.hash || "/", viewport: vpName, theme,
          before: null, after: null, identical: false, missingBefore: false, missingAfter: false,
          consoleErrors: { before: [], after: [] } };
        for (const side of ["before", "after"]) {
          const S = sides[side];
          const miss = side === "before" ? "missingBefore" : "missingAfter";
          if (sc.needsRoute && !S.routes.has(sc.needsRoute)) { rec[miss] = true; continue; }
          try {
            const r = await shoot(browser.cdp, { url: `http://127.0.0.1:${S.port}/${sc.hash ?? ""}`, vp, theme,
              signedOut: sc.signedOut, steps: sc.steps, needsSelector: sc.needsSelector, fullPage: sc.fullPage !== false });
            rec.consoleErrors[side] = [...new Set(r.errors)];
            if (r.missing) { rec[miss] = true; continue; }
            writeFileSync(join(OUT, side, `${id}.png`), r.png);
            rec[side] = `${side}/${id}.png`;
            if (r.cut) rec.cutAt = CAP_HEIGHT;
          } catch (e) {
            rec.consoleErrors[side].push(`[shots] ${e.message}`);
          }
        }
        if (rec.before && rec.after) rec.identical = readFileSync(join(OUT, rec.before)).equals(readFileSync(join(OUT, rec.after)));
        shots.push(rec);
        const tag = rec.missingBefore ? "new" : rec.missingAfter ? "gone" : rec.identical ? "same" : "changed";
        const errs = rec.consoleErrors.before.length + rec.consoleErrors.after.length;
        console.log(`${id.padEnd(30)} ${tag}${errs ? `, ${errs} console error(s)` : ""}`);
      }
    }
  }
} finally {
  await browser.cdp.send("Browser.close").catch(() => {});
  browser.cdp.ws.close();
  for (const S of Object.values(sides)) S.server.close();
  await new Promise((r) => (browser.proc.exitCode !== null ? r() : browser.proc.once("exit", r)));
  for (let i = 0; i < 10; i++) {
    try { rmSync(browser.profile, { recursive: true, force: true }); break; } catch { await sleep(300); }
  }
  if (!flags.has("--keep")) rmSync(join(OUT, "src"), { recursive: true, force: true });
}

const manifest = {
  base: { ref: BASE, sha: sides.before.sha }, head: { ref: HEAD, sha: sides.after.sha },
  browser: bin, fonts: flags.has("--fonts"), made: new Date().toISOString(), shots
};
writeFileSync(join(OUT, "manifest.json"), JSON.stringify(manifest, null, 1) + "\n");
const n = (f) => shots.filter(f).length;
console.log(`\n${shots.length} shots: ${n((s) => s.identical)} identical, ${n((s) => s.before && s.after && !s.identical)} changed, ` +
  `${n((s) => s.missingBefore)} missing before, ${n((s) => s.missingAfter)} missing after, ` +
  `${n((s) => s.consoleErrors.before.length || s.consoleErrors.after.length)} with console errors\n${join(OUT, "manifest.json")}`);
